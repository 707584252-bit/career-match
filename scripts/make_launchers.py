#!/usr/bin/env python3
"""生成 Windows 本机启动器 ``run.cmd`` / ``terminal.cmd``。

为什么需要「生成」而不是直接手写
--------------------------------
这两个文件踩过一次真实的坑：用普通文本工具写出来的是**裸 LF** 行尾，而
Windows 批处理必须是 **CRLF**。cmd.exe 解析不了，``goto`` 标签对不上，用户
双击时窗口一闪就关，菜单里全是乱码 —— 症状就是「run 打不开」，而且没有任何
报错，非常难查。

所以这里把两个文件当作**生成物**：

* 行尾统一写 ``\\r\\n``（``newline=""`` + 显式 CRLF，不受平台默认影响）；
* 内容保持**纯 ASCII**，控制台代码页是 936 还是 65001 都无所谓；
* 里面需要写死的本机绝对路径（Python、PortableGit）由本脚本探测，写错不了。

中文菜单不在这里 —— 它在 ``scripts/menu.py`` 里，由 Python 输出。

用法::

    python scripts/make_launchers.py            # 生成/覆盖两个启动器
    python scripts/make_launchers.py --check    # 只检查，不写文件（CI/测试用）
"""

from __future__ import annotations

import argparse
import shutil
import sys
from pathlib import Path

_ROOT = Path(__file__).resolve().parent.parent

RUN_CMD = "run.cmd"
TERMINAL_CMD = "terminal.cmd"

#: PortableGit 在本机的已知位置（PortableGit 没有右键菜单入口，只能靠路径找）
_BASH_CANDIDATES = (
    Path(r"E:\LenovoSoftstore\Install\WorkBuddy\resources\vendor\PortableGit\bin\bash.exe"),
    Path(r"C:\Program Files\Git\bin\bash.exe"),
)


def _python_exe() -> str:
    """当前解释器路径。启动器与生成它的解释器保持一致，避免版本错配。"""
    return sys.executable


def _bash_exe() -> str | None:
    """找一个可用的 bash；找不到返回 ``None``。"""
    for p in _BASH_CANDIDATES:
        if p.is_file():
            return str(p)
    return shutil.which("bash")


def render_run_cmd() -> str:
    py = _python_exe()
    return (
        "@echo off\r\n"
        "rem career-compass local launcher -- ASCII only, CRLF only.\r\n"
        "rem This file is GENERATED by scripts/make_launchers.py; edit that instead.\r\n"
        "rem Keep it dumb: the interactive menu lives in scripts\\menu.py, so neither\r\n"
        "rem the console codepage nor a stray LF can break it.\r\n"
        'cd /d "%~dp0"\r\n'
        "setlocal\r\n"
        f'set "PY={py}"\r\n'
        "\r\n"
        "rem Pass-through: run.cmd <subcommand> ... forwards to the CLI verbatim\r\n"
        'if not "%~1"=="" (\r\n'
        '    "%PY%" -m career_compass %*\r\n'
        "    exit /b %errorlevel%\r\n"
        ")\r\n"
        "\r\n"
        "title career-compass\r\n"
        '"%PY%" scripts\\menu.py\r\n'
        "if errorlevel 1 pause\r\n"
        "exit /b 0\r\n"
    )


def render_terminal_cmd() -> str:
    bash = _bash_exe()
    head = (
        "@echo off\r\n"
        "rem Opens a Git terminal in the project folder.\r\n"
        "rem GENERATED by scripts/make_launchers.py -- ASCII only, CRLF only.\r\n"
        'cd /d "%~dp0"\r\n'
        "title Git terminal - career-compass\r\n"
        "echo.\r\n"
        "echo   Git terminal opened. Current folder:\r\n"
        "echo   %CD%\r\n"
        "echo   You can paste git commands at the prompt below.\r\n"
        "echo.\r\n"
    )
    if bash is None:
        return (
            head
            + "echo   [!] bash not found. Install Git for Windows and rerun make_launchers.py.\r\npause\r\n"
        )
    return head + f'"{bash}" --login -i\r\n'


def _write_if_changed(path: Path, text: str) -> bool:
    """按字节比较后再写，避免无谓地刷新 mtime。返回是否发生了写入。"""
    data = text.encode("ascii")
    if path.is_file() and path.read_bytes() == data:
        return False
    path.write_bytes(data)
    return True


def problems() -> list[str]:
    """返回启动器当前存在的问题描述；健康时返回空列表。"""
    issues: list[str] = []
    for name in (RUN_CMD, TERMINAL_CMD):
        p = _ROOT / name
        if not p.is_file():
            issues.append(f"{name}: 不存在")
            continue
        raw = p.read_bytes()
        bare_lf = raw.count(b"\n") - raw.count(b"\r\n")
        if bare_lf:
            issues.append(f"{name}: 有 {bare_lf} 个裸 LF 行尾（批处理必须 CRLF，否则双击无反应）")
        if any(b > 0x7F for b in raw):
            issues.append(f"{name}: 含非 ASCII 字节（会受控制台代码页影响）")
    return issues


def main(argv: list[str] | None = None) -> int:
    from career_compass.console import ensure_utf8_output

    ensure_utf8_output()

    ap = argparse.ArgumentParser(description="生成 Windows 本机启动器")
    ap.add_argument("--check", action="store_true", help="只检查现状，不写文件")
    args = ap.parse_args(argv)

    if args.check:
        issues = problems()
        if issues:
            for i in issues:
                print(f"[x] {i}")
            return 1
        print("[ok] run.cmd / terminal.cmd 行尾与编码都正常。")
        return 0

    wrote = []
    if _write_if_changed(_ROOT / RUN_CMD, render_run_cmd()):
        wrote.append(RUN_CMD)
    if _write_if_changed(_ROOT / TERMINAL_CMD, render_terminal_cmd()):
        wrote.append(TERMINAL_CMD)

    if wrote:
        print(f"[ok] 已生成：{', '.join(wrote)}")
    else:
        print("[ok] 两个启动器内容已是最新，无需改动。")

    issues = problems()
    if issues:  # pragma: no cover - 生成逻辑自检，正常不会走到
        for i in issues:
            print(f"[x] {i}")
        return 1
    print("[ok] 自检通过：纯 ASCII + CRLF。")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
